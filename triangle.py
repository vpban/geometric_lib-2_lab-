def area(a, b):
    '''
    принимает значения a и b и возвращает площадь треугольника

        параметры:
            a (int): высота треугольника
            b (int): основание треугольника

        Возвращаемое значение:
            (int): площадь треугольника
    '''
    return a*b/2

def perimeter(a, b, c):
    '''
    принимает значения a, b и c и возвращает периметр треугольника

        параметры:
            a (int): первая сторона треугольника
            b (int): вторая сторона треугольника
            c (int): третья сторона треугольника

        Возвращаемое значение:
            (int): периметр треугольника
    '''
    return a+b+c
