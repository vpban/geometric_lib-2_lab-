def area(a, b):
    '''
    принимает значения a и b и возвращает площадь треугольника

        параметры:
            a(float/int): высота треугольника
            b(float/int): основание треугольника

        Возвращаемое значение:
            float/int: площадь треугольника
    '''
    return a*b/2

def perimeter(a, b, c):
    '''
    принимает значения a, b и c и возвращает периметр треугольника

        параметры:
            a(float/int): первая сторона треугольника
            b(float/int): вторая сторона треугольника
            c(float/int): третья сторона треугольника

        Возвращаемое значение:
            float/int: периметр треугольника
    '''
    return a+b+c
