import math


def area(r):
    '''
    принимает значение r и возвращает площадь круга

        параметры:
            r (int): радиус круга

        Возвращаемое значение:
            int: площадь круга
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    принимает значение r и возвращает периметр круга

        параметры:
            r (int): радиус круга

        Возвращаемое значение:
            int: периметр круга
    '''
    return 2 * math.pi * r

