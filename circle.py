import math


def area(r):
    '''
    принимает значение r и возвращает площадь круга

        параметры:
            r: радиус круга

        Возвращаемое значение:
            площадь круга
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    принимает значение r и возвращает периметр круга

        параметры:
            r: радиус круга

        Возвращаемое значение:
            периметр круга
    '''
    return 2 * math.pi * r

