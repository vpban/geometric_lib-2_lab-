
def area(a):
    '''
    принимает значение a и возвращает площадь квадрата

        параметры:
            a (int): сторона квадрата
        Возвращаемое значение:
            (int): площадь квадрата
    '''
    return a * a


def perimeter(a):
    '''
    принимает значение a и возвращает периметр квадрата

        параметры:
            a (int): сторона квадрата

        Возвращаемое значение:
            (int): периметр квадрата
    '''
    return 4 * a
