def area(a, b):
    '''
    принимает значения a, b и возвращает площадь прямоугольника

        параметры:
            a: первая сторона прямоугольника
            b: вторая сторона прямоугольника

        Возвращаемое значение:
            площадь прямоугольника
    '''
    return a*b

def perimeter(a,b):
    '''
    принимает значения a, b и возвращает периметр прямоугольника

        параметры:
            a: первая сторона прямоугольника
            b: вторая сторона прямоугольника

        Возвращаемое значение:
            периметр прямоугольника
    '''
    return 2*(a+b)
