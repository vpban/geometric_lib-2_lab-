def area(a, b):
    '''
    принимает значения a, b и возвращает площадь прямоугольника

        параметры:
            a (int): первая сторона прямоугольника
            b (int): вторая сторона прямоугольника

        Возвращаемое значение:
            (int): площадь прямоугольника
    '''
    return a*b

def perimeter(a,b):
    '''
    принимает значения a, b и возвращает периметр прямоугольника

        параметры:
            a (int): первая сторона прямоугольника
            b (int): вторая сторона прямоугольника

        Возвращаемое значение:
            (int): периметр прямоугольника
    '''
    return 2*(a+b)
